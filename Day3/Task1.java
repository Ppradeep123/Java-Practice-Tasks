package Day3;
// print 1 to 50 numbers using for loop

public class Task1 {
    public static void main (String args[]){

        for(int i=1;i<=50;i++){
            System.out.println(i);
        }
// while loop
        int a=1;
        while(a<=5){
            System.out.println(a);
            a++;
        }

        //do while loop
        int b=1;
        do{
            System.out.println(b);
            b++; }
            while(b<=5);
    }
}